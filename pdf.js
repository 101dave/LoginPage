// Scholog — Daily attendance PDF builder.
// Kept dependency-free (the jsPDF instance is injected) so it can be unit
// tested in Node with the same jsPDF build the browser loads.
(function (root) {
    "use strict";

    var STATUS_ORDER = ["Present", "Late", "Absent", "Excused"];

    function safeFilenamePart(value, fallback) {
        var cleaned = String(value == null ? "" : value)
            .replace(/[\\/:*?"<>|]+/g, "-")
            .replace(/\s+/g, " ")
            .trim();
        return cleaned || fallback;
    }

    function summarize(students, attendance, date) {
        var counts = { Present: 0, Late: 0, Absent: 0, Excused: 0 };
        students.forEach(function (student) {
            var status = attendance[date + "_" + student.student_id] || "Present";
            if (counts[status] === undefined) counts[status] = 0;
            counts[status] += 1;
        });
        return counts;
    }

    /**
     * Draw the daily attendance report on an existing jsPDF instance.
     * @param {object} doc  jsPDF instance (with the AutoTable plugin)
     * @param {{section:string,date:string,students:Array,attendance:Object,generatedAt?:Date,teacher?:string}} opts
     * @returns {{filename:string,counts:Object,rows:Array}}
     */
    function buildDailyAttendancePdf(doc, opts) {
        var options = opts || {};
        var section = String(options.section || "Section");
        var date = String(options.date || "");
        var students = Array.isArray(options.students) ? options.students : [];
        var attendance = options.attendance || {};
        var generatedAt = options.generatedAt instanceof Date ? options.generatedAt : new Date();

        if (typeof doc.autoTable !== "function") {
            throw new Error("PDF table plugin is unavailable. Please refresh the page.");
        }

        var counts = summarize(students, attendance, date);
        var total = students.length;
        var rows = students.map(function (student, index) {
            return [
                index + 1,
                student.name || "",
                student.student_id || "",
                attendance[date + "_" + student.student_id] || "Present"
            ];
        });

        // Header
        doc.setFont("helvetica", "bold");
        doc.setFontSize(16);
        doc.text("Scholog — Daily Attendance Report", 14, 18);

        doc.setFont("helvetica", "normal");
        doc.setFontSize(10);
        doc.text("Section: " + section, 14, 27);
        doc.text("Date: " + date, 14, 33);
        if (options.teacher) doc.text("Teacher: " + options.teacher, 14, 39);

        var generatedLabel = "Generated: " + generatedAt.toLocaleString();
        doc.setFontSize(8);
        doc.setTextColor(110);
        doc.text(generatedLabel, 14, options.teacher ? 45 : 39);
        doc.setTextColor(0);

        doc.autoTable({
            startY: options.teacher ? 50 : 44,
            head: [["#", "Student Name", "Student ID", "Status"]],
            body: rows.length ? rows : [["—", "No students in this section", "—", "—"]],
            styles: { fontSize: 9, cellPadding: 2.5 },
            headStyles: { fillColor: [15, 23, 42], textColor: 255, fontStyle: "bold" },
            alternateRowStyles: { fillColor: [248, 250, 252] },
            columnStyles: { 0: { cellWidth: 12, halign: "center" }, 3: { cellWidth: 30 } },
            margin: { left: 14, right: 14 }
        });

        var y = (doc.lastAutoTable && doc.lastAutoTable.finalY ? doc.lastAutoTable.finalY : 60) + 10;
        doc.setFontSize(10);
        doc.setFont("helvetica", "bold");
        doc.text("Summary", 14, y);
        doc.setFont("helvetica", "normal");
        doc.text(
            "Present: " + counts.Present + "    Late: " + counts.Late +
            "    Absent: " + counts.Absent + "    Excused: " + counts.Excused +
            "    Total: " + total,
            14,
            y + 6
        );

        var rate = total > 0 ? Math.round(((counts.Present + counts.Late) / total) * 100) : 0;
        doc.text("Attendance rate (Present + Late): " + rate + "%", 14, y + 12);

        doc.setFontSize(8);
        doc.setTextColor(110);
        doc.text("Generated by Scholog — Student & Attendance Tracker", 14, y + 22);
        doc.setTextColor(0);

        var pageCount = doc.getNumberOfPages ? doc.getNumberOfPages() : 1;
        for (var page = 1; page <= pageCount; page++) {
            doc.setPage(page);
            doc.setFontSize(8);
            doc.text(
                "Page " + page + " of " + pageCount,
                doc.internal.pageSize.getWidth() - 14,
                doc.internal.pageSize.getHeight() - 8,
                { align: "right" }
            );
        }

        return {
            filename: "Daily_Attendance_" + safeFilenamePart(section, "Section") + "_" +
                (safeFilenamePart(date, "date")) + ".pdf",
            counts: counts,
            rows: rows
        };
    }

    var api = {
        buildDailyAttendancePdf: buildDailyAttendancePdf,
        summarize: summarize,
        safeFilenamePart: safeFilenamePart,
        STATUS_ORDER: STATUS_ORDER
    };

    if (typeof module === "object" && module.exports) module.exports = api;
    if (root) root.SchologPdf = api;
})(typeof globalThis !== "undefined" ? globalThis : this);
