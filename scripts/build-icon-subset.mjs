// Generate `vendor/lucide-subset.js` from the full Lucide build.
//
// Scholog uses 38 of Lucide's 1,743 icons, but main.html shipped the whole
// library (~350 KB). This script extracts just the icons the app references and
// writes a drop-in replacement that exposes the same `window.lucide.createIcons()`
// API, preserving element attributes (class, style, aria-*) exactly like Lucide.
//
// Run after adding or removing a `data-lucide="..."` icon:
//   node scripts/build-icon-subset.mjs
// `tests/icons.test.mjs` fails when a referenced icon is missing from the bundle.

import fs from "node:fs";
import path from "node:path";
import { JSDOM } from "jsdom";

const ROOT = path.resolve(import.meta.dirname, "..");
const SOURCES = ["main.html", "main.js", "scan.html", "scan.js", "student-record.html", "student-record.js", "index.html", "script.js"];
const FULL_LIBRARY = path.join(ROOT, "vendor/lucide.min.js");
const OUTPUT = path.join(ROOT, "vendor/lucide-subset.js");

// ------------------------------------------------------------------ icon names

export function usedIconNames() {
    const names = new Set();
    for (const file of SOURCES) {
        const full = path.join(ROOT, file);
        if (!fs.existsSync(full)) continue;
        const source = fs.readFileSync(full, "utf8");
        for (const match of source.matchAll(/data-lucide="([a-z0-9-]+)"/g)) {
            names.add(match[1]);
        }
    }
    return [...names].sort();
}

const toPascal = (name) => name
    .split("-")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

// --------------------------------------------------------------- build bundle

export function buildSubset() {
    const dom = new JSDOM("<!doctype html><html><body></body></html>", { runScripts: "outside-only" });
    dom.window.eval(fs.readFileSync(FULL_LIBRARY, "utf8"));
    const library = dom.window.lucide;
    if (!library || !library.icons) throw new Error("Could not read the Lucide icon data.");

    const wanted = usedIconNames();
    const picked = {};
    const missing = [];
    for (const name of wanted) {
        const key = library.icons[toPascal(name)] ? toPascal(name) : name;
        const node = library.icons[key];
        if (!node) {
            missing.push(name);
            continue;
        }
        picked[name] = node;
    }
    if (missing.length > 0) {
        throw new Error(`Lucide has no icon for: ${missing.join(", ")}`);
    }

    const body = `/**
 * @license Generated from lucide v0.469.0 - ISC
 *
 * Subset build: ${wanted.length} icons used by Scholog, generated by
 * scripts/build-icon-subset.mjs. Do not edit by hand; regenerate instead.
 * Replaces the full 350 KB library and keeps the same public API:
 *   window.lucide.createIcons()
 */
(function (global) {
    "use strict";

    var ICONS = ${JSON.stringify(picked)};

    var SVG_NS = "http://www.w3.org/2000/svg";
    var DEFAULT_ATTRS = {
        xmlns: SVG_NS,
        width: 24,
        height: 24,
        viewBox: "0 0 24 24",
        fill: "none",
        stroke: "currentColor",
        "stroke-width": 2,
        "stroke-linecap": "round",
        "stroke-linejoin": "round"
    };

    function toPascalCase(name) {
        return String(name || "")
            .split("-")
            .filter(Boolean)
            .map(function (part) { return part.charAt(0).toUpperCase() + part.slice(1); })
            .join("");
    }

    function nodeToElement(node) {
        var element = document.createElementNS(SVG_NS, node[0]);
        var attrs = node[1] || {};
        Object.keys(attrs).forEach(function (key) {
            element.setAttribute(key, attrs[key]);
        });
        (node[2] || []).forEach(function (child) {
            element.appendChild(nodeToElement(child));
        });
        return element;
    }

    function elementToSvg(name, source) {
        var node = ICONS[name] || ICONS[toPascalCase(name)];
        if (!node) return null;

        var svg = nodeToElement(node);
        // Lucide keeps every attribute of the placeholder (class, style, aria-*)
        // except the marker itself, so inline sizing keeps working.
        if (source && source.attributes) {
            Array.prototype.forEach.call(source.attributes, function (attr) {
                if (attr.name === "data-lucide") return;
                if (attr.name === "class") return;
                svg.setAttribute(attr.name, attr.value);
            });
        }
        var classes = "lucide lucide-" + name;
        var extra = source && source.getAttribute ? source.getAttribute("class") : "";
        svg.setAttribute("class", extra ? classes + " " + extra : classes);
        svg.setAttribute("aria-hidden", source && source.getAttribute("aria-hidden") === "false" ? "false" : "true");
        return svg;
    }

    function createIcons(options) {
        var opts = options || {};
        var nameAttr = opts.nameAttr || "data-lucide";
        var attrs = opts.attrs || {};
        var elements = document.querySelectorAll("[" + nameAttr + "]");
        Array.prototype.forEach.call(elements, function (element) {
            var name = (element.getAttribute(nameAttr) || "").trim();
            if (!name) return;
            var svg = elementToSvg(name, element);
            if (!svg) {
                console.warn("Scholog icon subset is missing:", name, "- run scripts/build-icon-subset.mjs");
                return;
            }
            Object.keys(attrs).forEach(function (key) { svg.setAttribute(key, attrs[key]); });
            if (element.parentNode) element.replaceWith(svg);
        });
    }

    var api = { createIcons: createIcons, icons: ICONS, toPascalCase: toPascalCase, version: "0.469.0-subset" };
    global.lucide = api;
    if (typeof module === "object" && module.exports) module.exports = api;
})(typeof globalThis !== "undefined" ? globalThis : this);
`;

    fs.writeFileSync(OUTPUT, body, "utf8");
    const before = fs.statSync(FULL_LIBRARY).size;
    const after = fs.statSync(OUTPUT).size;
    return { icons: wanted, before, after };
}

if (process.argv[1] && process.argv[1].endsWith("build-icon-subset.mjs")) {
    const result = buildSubset();
    console.log(`Extracted ${result.icons.length} icons: ${result.icons.join(", ")}`);
    console.log(`vendor/lucide.min.js ${(result.before / 1024).toFixed(1)} KB -> vendor/lucide-subset.js ${(result.after / 1024).toFixed(1)} KB`);
}
